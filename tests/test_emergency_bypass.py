"""
tests/test_emergency_bypass.py
────────────────────────────────
Tests for the EMERGENCY BYPASS mechanism.

The most critical test in this suite:
  → When a CRITICAL message is processed, the generative AI/RAG invocation count MUST be 0.

Coverage
────────
  TC-EB-01  CRITICAL message → emergency=True, bypass_llm=True
  TC-EB-02  LLM invocation count is ZERO for CRITICAL messages (key safety test)
  TC-EB-03  Emergency resources are served from config, not generated by AI
  TC-EB-04  CRITICAL response contains crisis message, not generic chat
  TC-EB-05  Non-critical message → bypass_llm=False (bypass does not over-fire)
  TC-EB-06  next_action is EMERGENCY_SUPPORT for CRITICAL messages
  TC-EB-07  state is EMERGENCY_RESPONSE for CRITICAL messages
  TC-EB-08  Emergency endpoint returns contacts without LLM
"""

import pytest
from fastapi.testclient import TestClient

from app.main import app
from app.services.risk_detector import RiskDetector
from app.schemas.triage_schema import RiskLevel


@pytest.fixture(scope="module")
def client() -> TestClient:
    return TestClient(app)


CRITICAL_MESSAGES = [
    "I want to end my life tonight.",
    "I am going to hurt myself.",
    "I have been cutting my wrists.",
    "I took an overdose of pills.",
    "I have written my goodbye note.",
    "I am thinking about suicide and I have a plan.",
    "Everyone would be better off without me and I am ready to end it.",
    "I am giving away all my belongings because I am done with everything.",
]

NON_CRITICAL_MESSAGES = [
    "I am stressed about my exams.",
    "I cannot manage my coursework deadlines.",
    "I need help with financial aid.",
    "How do I apply for a disability accommodation?",
    "I feel anxious before my exams.",
]


class TestEmergencyBypass:
    """TC-EB-01 through TC-EB-07"""

    @pytest.mark.parametrize("message", CRITICAL_MESSAGES)
    def test_critical_message_triggers_bypass(self, client, message):
        """TC-EB-01: Every CRITICAL message must set emergency=True and bypass_llm=True."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": message},
        )
        assert response.status_code == 200
        data = response.json()
        assert data["emergency"] is True, f"Expected emergency=True for: {message!r}"
        assert data["bypass_llm"] is True, f"Expected bypass_llm=True for: {message!r}"

    @pytest.mark.parametrize("message", CRITICAL_MESSAGES)
    def test_llm_invocation_count_is_zero_for_critical(self, client, message):
        """
        TC-EB-02: THE KEY SAFETY TEST.

        When a CRITICAL message is detected, the LLM invocation count
        in the response metadata MUST be 0.

        This proves the generative AI pipeline was never reached.
        """
        response = client.post(
            "/api/triage/analyze",
            json={"message": message},
        )
        assert response.status_code == 200
        data = response.json()

        # Primary assertion: risk must be CRITICAL
        assert data["risk_level"] == "CRITICAL", (
            f"Expected CRITICAL risk for: {message!r}, got {data['risk_level']}"
        )

        # Key safety assertion: LLM invocation count is 0
        llm_count = data.get("routing_metadata", {}).get("llm_invocation_count", -1)
        assert llm_count == 0, (
            f"LLM invocation count must be 0 for CRITICAL messages. "
            f"Got: {llm_count} for message: {message!r}"
        )

    def test_critical_response_state_is_emergency(self, client):
        """TC-EB-07: State must be EMERGENCY_RESPONSE for CRITICAL messages."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": "I want to kill myself."},
        )
        data = response.json()
        assert data["state"] == "EMERGENCY_RESPONSE"

    def test_critical_next_action_is_emergency_support(self, client):
        """TC-EB-06: next_action must be EMERGENCY_SUPPORT for CRITICAL messages."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": "I am going to end my life tonight."},
        )
        data = response.json()
        assert data["next_action"] == "EMERGENCY_SUPPORT"

    def test_critical_response_contains_human_support_message(self, client):
        """TC-EB-04: The emergency message must reference human support, not AI chat."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": "I want to end my life."},
        )
        data = response.json()
        msg = data.get("message", "").lower()
        # Must mention support, emergency services, or human help
        human_keywords = ["support", "emergency", "help", "human", "contact", "alone"]
        assert any(kw in msg for kw in human_keywords), (
            f"Emergency message should reference human support. Got: {data['message']!r}"
        )

    def test_bypass_does_not_fire_for_low_risk(self, client):
        """TC-EB-05: Normal messages must NOT trigger emergency bypass."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": "I am stressed about my upcoming exams."},
        )
        data = response.json()
        assert data["emergency"] is False
        assert data["bypass_llm"] is False
        assert data["risk_level"] != "CRITICAL"

    @pytest.mark.parametrize("message", NON_CRITICAL_MESSAGES)
    def test_non_critical_messages_not_bypassed(self, client, message):
        """TC-EB-05 (parametrised): Non-critical messages → bypass_llm=False."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": message},
        )
        assert response.status_code == 200
        data = response.json()
        assert data["emergency"] is False, (
            f"Non-critical message should not trigger emergency bypass: {message!r}"
        )


class TestEmergencyResourcesEndpoint:
    """TC-EB-08: Emergency resources endpoint."""

    def test_emergency_endpoint_returns_contacts(self, client):
        """Emergency endpoint returns contact data from config file."""
        response = client.post("/api/triage/emergency")
        assert response.status_code == 200
        data = response.json()
        assert "emergency_contacts" in data
        assert isinstance(data["emergency_contacts"], list)
        # Must have at least one contact
        assert len(data["emergency_contacts"]) > 0

    def test_emergency_contacts_have_required_fields(self, client):
        """Each emergency contact must have an id, name, type, and description."""
        response = client.post("/api/triage/emergency")
        data = response.json()
        for contact in data["emergency_contacts"]:
            assert "id" in contact
            assert "name" in contact
            assert "type" in contact
            assert "description" in contact

    def test_emergency_endpoint_includes_disclaimer(self, client):
        """Emergency response must include global disclaimer."""
        response = client.post("/api/triage/emergency")
        data = response.json()
        assert "global_disclaimer" in data
        assert len(data["global_disclaimer"]) > 0

    def test_critical_triage_response_includes_resources(self, client):
        """TC-EB-03: CRITICAL triage response resources come from config, not LLM."""
        response = client.post(
            "/api/triage/analyze",
            json={"message": "I want to kill myself right now."},
        )
        data = response.json()
        assert data["risk_level"] == "CRITICAL"
        # Resources array should be present (may be empty if config has no verified contacts,
        # but must not be absent)
        assert "resources" in data
        assert isinstance(data["resources"], list)

